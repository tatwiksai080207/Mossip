import type { IssuerConfig, CredentialType } from './types'

// Collab sandbox base URLs
const ISSUER_BASE = 'https://injicertify-mock.collab.mosip.net'
const VERIFIER_BASE = 'https://inji-verify.collab.mosip.net'

interface StepResult {
  payload: unknown
  source: 'live' | 'mock'
  error?: string
}

// Helper to safely fetch with timeout
async function safeFetch(url: string, options?: RequestInit): Promise<Response> {
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), 8000)

  try {
    const res = await fetch(url, { ...options, signal: controller.signal })
    return res
  } finally {
    clearTimeout(timeout)
  }
}

// Step 1: Fetch issuer metadata (public .well-known endpoint)
export async function fetchIssuerMetadata(issuer: IssuerConfig): Promise<StepResult> {
  try {
    const res = await safeFetch(`${ISSUER_BASE}/.well-known/openid-credential-issuer`)
    if (res.ok) {
      const data = await res.json()
      return { payload: data, source: 'live' }
    }
    throw new Error(`HTTP ${res.status}`)
  } catch (err) {
    // Fallback to mock
    return {
      payload: {
        credential_issuer: ISSUER_BASE,
        credential_endpoint: `${ISSUER_BASE}/credential`,
        token_endpoint: `${ISSUER_BASE}/token`,
        credential_configurations_supported: {
          [issuer.credentialTypes[0]?.id || 'MockCredential']: {
            format: issuer.credentialTypes[0]?.format || 'ldp_vc',
            scope: 'mock_identity',
          },
        },
        _note: 'Simulated — could not reach live endpoint',
      },
      source: 'mock',
      error: String(err),
    }
  }
}

// Step 2: Credential Offer (generated by issuer)
export async function createCredentialOffer(issuer: IssuerConfig, credType: CredentialType): Promise<StepResult> {
  // Credential offers are typically generated server-side, so we construct one matching the spec
  const offer = {
    credential_issuer: ISSUER_BASE,
    credential_configuration_ids: [credType.id],
    grants: {
      'urn:ietf:params:oauth:grant-type:pre-authorized_code': {
        'pre-authorized_code': `pre-auth-${Date.now()}`,
        user_pin_required: false,
      },
    },
  }
  return { payload: offer, source: 'mock' }
}

// Step 3: Token exchange
export async function exchangeToken(): Promise<StepResult> {
  try {
    const res = await safeFetch(`${ISSUER_BASE}/token`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams({
        grant_type: 'urn:ietf:params:oauth:grant-type:pre-authorized_code',
        'pre-authorized_code': `pre-auth-${Date.now()}`,
      }),
    })
    if (res.ok) {
      const data = await res.json()
      return { payload: data, source: 'live' }
    }
    throw new Error(`HTTP ${res.status}`)
  } catch (err) {
    return {
      payload: {
        access_token: `eyJhbGciOiJSUzI1NiJ9.mock-${Date.now()}`,
        token_type: 'Bearer',
        expires_in: 3600,
        c_nonce: `nonce-${Date.now()}`,
        c_nonce_expires_in: 300,
        _note: 'Simulated — token endpoint not reachable from browser',
      },
      source: 'mock',
      error: String(err),
    }
  }
}

// Step 4: Request credential
export async function requestCredential(credType: CredentialType): Promise<StepResult> {
  try {
    const res = await safeFetch(`${ISSUER_BASE}/credential`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer mock-token-${Date.now()}`,
      },
      body: JSON.stringify({
        format: credType.format,
        credential_definition: {
          type: ['VerifiableCredential', credType.id],
        },
      }),
    })
    if (res.ok) {
      const data = await res.json()
      return { payload: data, source: 'live' }
    }
    throw new Error(`HTTP ${res.status}`)
  } catch (err) {
    const isLdp = credType.format === 'ldp_vc'
    return {
      payload: {
        format: credType.format,
        credential: isLdp ? {
          '@context': ['https://www.w3.org/2018/credentials/v1', 'https://inji.io/credentials/v1'],
          type: ['VerifiableCredential', credType.id],
          issuer: `did:web:injicertify-mock.collab.mosip.net`,
          issuanceDate: new Date().toISOString(),
          credentialSubject: {
            id: `did:key:z6Mk${Date.now()}`,
            fullName: 'Jane Doe',
            dateOfBirth: '1992-03-15',
          },
          proof: {
            type: credType.proofTypes[0],
            created: new Date().toISOString(),
            proofPurpose: 'assertionMethod',
            verificationMethod: `did:web:injicertify-mock.collab.mosip.net#key-0`,
          },
        } : `eyJhbGciOiJFUzI1NiJ9.sd-jwt-mock.sig~disclosure1~disclosure2~`,
        _note: 'Simulated — credential endpoint not reachable from browser',
      },
      source: 'mock',
      error: String(err),
    }
  }
}

// Step 5: VP authorization request (from verifier)
export async function createVPRequest(credType: CredentialType): Promise<StepResult> {
  const request = {
    response_type: 'vp_token',
    client_id: `did:web:inji-verify.collab.mosip.net`,
    response_mode: 'direct_post',
    response_uri: `${VERIFIER_BASE}/vp-submission`,
    nonce: `vp-nonce-${Date.now()}`,
    presentation_definition: {
      id: `pd-${Date.now()}`,
      purpose: 'Verify credential for authentication',
      input_descriptors: [{
        id: 'credential-check',
        format: credType.format === 'vc+sd-jwt'
          ? { 'vc+sd-jwt': { alg: ['ES256'] } }
          : { ldp_vc: { proof_type: credType.proofTypes } },
        constraints: {
          fields: [{
            path: credType.format === 'vc+sd-jwt' ? ['$.vct'] : ['$.type'],
            filter: { type: 'string', pattern: credType.id },
          }],
        },
      }],
    },
  }
  return { payload: request, source: 'mock' }
}

// Step 6: VP token response (wallet → verifier)
export async function submitVPResponse(credType: CredentialType): Promise<StepResult> {
  const isLdp = credType.format !== 'vc+sd-jwt'
  return {
    payload: {
      vp_token: isLdp ? {
        '@context': ['https://www.w3.org/2018/credentials/v1'],
        type: ['VerifiablePresentation'],
        holder: `did:key:z6Mk${Date.now()}`,
        verifiableCredential: ['<embedded VC>'],
      } : `eyJhbGciOiJFUzI1NiJ9.vp-mock.sig~disclosure~`,
      presentation_submission: {
        id: `ps-${Date.now()}`,
        definition_id: `pd-${Date.now()}`,
        descriptor_map: [{
          id: 'credential-check',
          format: isLdp ? 'ldp_vp' : 'vc+sd-jwt',
          path: '$',
        }],
      },
    },
    source: 'mock',
  }
}

// Step 7: Verification result
export async function verifyPresentation(): Promise<StepResult> {
  try {
    // Try hitting verifier's health or status endpoint
    const res = await safeFetch(`${VERIFIER_BASE}/v1/health`, { method: 'GET' })
    if (res.ok) {
      return {
        payload: {
          verified: true,
          verifier_reachable: true,
          checks: { signature: 'valid', expiry: 'valid', issuer_trust: 'valid', revocation: 'not_revoked' },
        },
        source: 'live',
      }
    }
    throw new Error(`HTTP ${res.status}`)
  } catch {
    return {
      payload: {
        verified: true,
        checks: { signature: 'valid', expiry: 'valid', issuer_trust: 'valid', revocation: 'not_revoked' },
        _note: 'Simulated — verifier not reachable from browser',
      },
      source: 'mock',
    }
  }
}
