import type { FlowStepInfo, IssuerConfig, WalletConfig, VerifierConfig, CredentialType } from '../../types'

interface Props {
  issuer: IssuerConfig
  wallet: WalletConfig
  verifier: VerifierConfig
  credentialType: CredentialType
  steps: FlowStepInfo[]
}

export default function TestReport({ issuer, wallet, verifier, credentialType, steps }: Props) {
  const isManualMode = wallet?.id === 'inji-wallet-interactive' || wallet?.id === 'inji-web-manual' || wallet?.id === 'inji-mobile'
  const failedSteps = steps.filter(s => s.status === 'error')
  const allPassed = failedSteps.length === 0 && (
    isManualMode 
      ? steps.find(s => s.id === 'verification')?.status === 'done' 
      : steps.every(s => s.status === 'done')
  )

  const downloadReport = (format: 'json' | 'md') => {
    const timestamp = new Date().toISOString()
    let content = ''
    let mimeType = 'application/json'
    let filename = `interop-report-${credentialType.format}-${Date.now()}`

    if (format === 'json') {
      const data = {
        generatedAt: timestamp,
        status: allPassed ? 'PASS' : 'FAIL',
        configuration: {
          issuer: { id: issuer.id, name: issuer.name, env: issuer.env },
          wallet: { id: wallet.id, name: wallet.name, env: wallet.env },
          verifier: { id: verifier.id, name: verifier.name, env: verifier.env },
          credentialType: {
            id: credentialType.id,
            name: credentialType.name,
            format: credentialType.format,
            proofTypes: credentialType.proofTypes,
            vct: credentialType.vct,
          },
        },
        steps: steps.map((s, i) => ({
          stepNumber: i + 1,
          id: s.id,
          label: s.label,
          status: s.status,
          source: s.source,
          payload: s.payload,
        })),
      }
      content = JSON.stringify(data, null, 2)
      mimeType = 'application/json'
      filename += '.json'
    } else {
      content = `# Verifiable Credentials Interoperability Test Report

**Generated:** ${timestamp}  
**Overall Result:** ${allPassed ? 'PASS' : 'FAIL'}  
**Credential Format Under Test:** \`${credentialType.format}\` (${credentialType.name})  
**Signature Suite / Alg:** \`${credentialType.proofTypes.join(', ')}\`  

---

## 1. Test Configuration

| Component | Entity Name | Environment | Protocol / Format |
|---|---|---|---|
| **Issuer** | ${issuer.name} | \`${issuer.env || 'unknown'}\` | OpenID4VCI |
| **Wallet** | ${wallet.name} | \`${wallet.env || 'unknown'}\` | Holder / Prover |
| **Verifier** | ${verifier.name} | \`${verifier.env || 'unknown'}\` | OpenID4VP |
| **Credential Type** | ${credentialType.name} | — | \`${credentialType.format}\` |

---

## 2. Protocol Step Execution Log

| # | Protocol Step | Status | Wire Source |
|---|---|---|---|
${steps.map((s, i) => `| ${i + 1} | ${s.label} | **${s.status.toUpperCase()}** | \`${s.source || 'n/a'}\` |`).join('\n')}

---

## 3. Step Diagnostics & Wire Payloads

${steps.map((s, i) => `### Step ${i + 1}: ${s.label} (${s.status.toUpperCase()})
- **Status:** \`${s.status}\`
- **Source:** \`${s.source || 'n/a'}\`

\`\`\`json
${JSON.stringify(s.payload || {}, null, 2)}
\`\`\`
`).join('\n\n')}

---

*Report generated by MOSIP Inji Interoperability Playground.*
`
      mimeType = 'text/markdown'
      filename += '.md'
    }

    const blob = new Blob([content], { type: mimeType })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  return (
    <div className="border border-app-border rounded-lg bg-app-card/40">
      <div className="px-4 py-3 border-b border-app-border flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <h3 className="text-sm font-medium text-app-text">Test Report</h3>
          <span className={`text-xs font-medium px-2 py-0.5 rounded ${
            allPassed
              ? 'bg-emerald-500/10 text-emerald-400'
              : 'bg-rose-500/10 text-rose-400'
          }`}>
            {allPassed ? 'PASS' : 'FAIL'}
          </span>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={() => downloadReport('md')}
            className="px-2.5 py-1 text-xs font-medium rounded bg-app-card hover:bg-app-card-hover text-app-text-secondary hover:text-app-text border border-app-border transition-colors flex items-center gap-1.5 cursor-pointer"
            title="Download report in Markdown format"
          >
            <svg className="w-3.5 h-3.5 text-app-text-muted" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4" />
            </svg>
            <span>Export .MD</span>
          </button>
          <button
            onClick={() => downloadReport('json')}
            className="px-2.5 py-1 text-xs font-medium rounded bg-app-card hover:bg-app-card-hover text-app-text-secondary hover:text-app-text border border-app-border transition-colors flex items-center gap-1.5 cursor-pointer"
            title="Download report in JSON format"
          >
            <svg className="w-3.5 h-3.5 text-app-text-muted" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4" />
            </svg>
            <span>Export JSON</span>
          </button>
        </div>
      </div>

      <div className="p-4 space-y-4">
        {/* Configuration used */}
        <div>
          <p className="text-xs text-app-text-muted mb-2">Configuration</p>
          <table className="w-full text-sm">
            <tbody className="divide-y divide-app-border/50">
              <tr>
                <td className="py-1.5 text-app-text-muted w-32">Issuer</td>
                <td className="py-1.5 text-app-text">{issuer.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-app-text-muted">Wallet</td>
                <td className="py-1.5 text-app-text">{wallet.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-app-text-muted">Verifier</td>
                <td className="py-1.5 text-app-text">{verifier.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-app-text-muted">Format</td>
                <td className="py-1.5">
                  <span className={`text-xs font-medium px-1.5 py-0.5 rounded ${
                    credentialType.format === 'vc+sd-jwt'
                      ? 'bg-purple-500/10 text-purple-400'
                      : 'bg-emerald-500/10 text-emerald-400'
                  }`}>
                    {credentialType.name}
                  </span>
                </td>
              </tr>
              <tr>
                <td className="py-1.5 text-app-text-muted">Proof Type</td>
                <td className="py-1.5 text-app-text font-mono text-xs">{credentialType.proofTypes.join(', ')}</td>
              </tr>
            </tbody>
          </table>
        </div>

        {/* Step results */}
        <div>
          <p className="text-xs text-app-text-muted mb-2">Step Results</p>
          <div className="space-y-1">
            {steps.map((step, i) => (
              <div key={step.id} className="flex items-center justify-between px-3 py-2 rounded-md bg-app-base/50 border border-app-border/50 text-sm">
                <div className="flex items-center gap-2">
                  <span className="text-app-text-muted text-xs w-4">{i + 1}.</span>
                  <span className="text-app-text">{step.label}</span>
                </div>
                <span className={`text-xs font-medium ${
                  step.status === 'done' ? 'text-emerald-400' :
                  step.status === 'error' ? 'text-rose-400' :
                  'text-app-text-muted'
                }`}>
                  {step.status === 'done' ? 'pass' : step.status}
                </span>
              </div>
            ))}
          </div>
        </div>

        {/* Failure details */}
        {failedSteps.length > 0 && (
          <div className="border border-app-border-focus rounded-xl p-3.5 bg-app-accent-subtle/30">
            <p className="text-xs text-app-accent font-semibold mb-1.5">Failed Steps (Interoperability Gaps)</p>
            <div className="space-y-1">
              {failedSteps.map(s => (
                <div key={s.id} className="flex items-center gap-1.5 text-xs text-app-text">
                  <svg className="w-3.5 h-3.5 text-rose-400 shrink-0" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                    <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
                  </svg>
                  <span>{s.label}</span>
                </div>
              ))}
            </div>
            <p className="text-xs text-app-text-muted mt-2 leading-relaxed">
              These failures represent real interoperability gaps discovered during testing against the
              MOSIP Collab sandbox. See <span className="font-mono text-app-accent">INTEROPERABILITY_REPORT.md</span> for details.
            </p>
          </div>
        )}
      </div>
    </div>
  )
}
