import type { FlowStepInfo, IssuerConfig, WalletConfig, VerifierConfig, CredentialType } from '../../types'

interface Props {
  issuer: IssuerConfig
  wallet: WalletConfig
  verifier: VerifierConfig
  credentialType: CredentialType
  steps: FlowStepInfo[]
}

export default function TestReport({ issuer, wallet, verifier, credentialType, steps }: Props) {
  const isManualMode = wallet?.id === 'inji-web-manual' || wallet?.id === 'inji-mobile'
  const failedSteps = steps.filter(s => s.status === 'error')
  const allPassed = failedSteps.length === 0 && (
    isManualMode 
      ? steps.find(s => s.id === 'verification')?.status === 'done' 
      : steps.every(s => s.status === 'done')
  )

  const downloadReport = (format: 'json' | 'md') => {
    const timestamp = new Date().toISOString()
    let content = ''
    let mimeType = 'application/json'
    let filename = `interop-report-${credentialType.format}-${Date.now()}`

    if (format === 'json') {
      const data = {
        generatedAt: timestamp,
        status: allPassed ? 'PASS' : 'FAIL',
        configuration: {
          issuer: { id: issuer.id, name: issuer.name, env: issuer.env },
          wallet: { id: wallet.id, name: wallet.name, env: wallet.env },
          verifier: { id: verifier.id, name: verifier.name, env: verifier.env },
          credentialType: {
            id: credentialType.id,
            name: credentialType.name,
            format: credentialType.format,
            proofTypes: credentialType.proofTypes,
            vct: credentialType.vct,
          },
        },
        steps: steps.map((s, i) => ({
          stepNumber: i + 1,
          id: s.id,
          label: s.label,
          status: s.status,
          source: s.source,
          payload: s.payload,
        })),
      }
      content = JSON.stringify(data, null, 2)
      mimeType = 'application/json'
      filename += '.json'
    } else {
      content = `# Verifiable Credentials Interoperability Test Report

**Generated:** ${timestamp}  
**Overall Result:** ${allPassed ? 'PASS' : 'FAIL'}  
**Credential Format Under Test:** \`${credentialType.format}\` (${credentialType.name})  
**Signature Suite / Alg:** \`${credentialType.proofTypes.join(', ')}\`  

---

## 1. Test Configuration

| Component | Entity Name | Environment | Protocol / Format |
|---|---|---|---|
| **Issuer** | ${issuer.name} | \`${issuer.env || 'unknown'}\` | OpenID4VCI |
| **Wallet** | ${wallet.name} | \`${wallet.env || 'unknown'}\` | Holder / Prover |
| **Verifier** | ${verifier.name} | \`${verifier.env || 'unknown'}\` | OpenID4VP |
| **Credential Type** | ${credentialType.name} | — | \`${credentialType.format}\` |

---

## 2. Protocol Step Execution Log

| # | Protocol Step | Status | Wire Source |
|---|---|---|---|
${steps.map((s, i) => `| ${i + 1} | ${s.label} | **${s.status.toUpperCase()}** | \`${s.source || 'n/a'}\` |`).join('\n')}

---

## 3. Step Diagnostics & Wire Payloads

${steps.map((s, i) => `### Step ${i + 1}: ${s.label} (${s.status.toUpperCase()})
- **Status:** \`${s.status}\`
- **Source:** \`${s.source || 'n/a'}\`

\`\`\`json
${JSON.stringify(s.payload || {}, null, 2)}
\`\`\`
`).join('\n\n')}

---

*Report generated by MOSIP Inji Interoperability Playground.*
`
      mimeType = 'text/markdown'
      filename += '.md'
    }

    const blob = new Blob([content], { type: mimeType })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  return (
    <div className="border border-slate-800 rounded-lg">
      <div className="px-4 py-3 border-b border-slate-800 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <h3 className="text-sm font-medium text-slate-300">Test Report</h3>
          <span className={`text-xs font-medium px-2 py-0.5 rounded ${
            allPassed
              ? 'bg-green-500/10 text-green-400'
              : 'bg-red-500/10 text-red-400'
          }`}>
            {allPassed ? 'PASS' : 'FAIL'}
          </span>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={() => downloadReport('md')}
            className="px-2.5 py-1 text-xs font-medium rounded bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-colors flex items-center gap-1.5"
            title="Download report in Markdown format"
          >
            <span>↓</span> Export .MD
          </button>
          <button
            onClick={() => downloadReport('json')}
            className="px-2.5 py-1 text-xs font-medium rounded bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-colors flex items-center gap-1.5"
            title="Download report in JSON format"
          >
            <span>↓</span> Export JSON
          </button>
        </div>
      </div>

      <div className="p-4 space-y-4">
        {/* Configuration used */}
        <div>
          <p className="text-xs text-slate-500 mb-2">Configuration</p>
          <table className="w-full text-sm">
            <tbody className="divide-y divide-slate-800/50">
              <tr>
                <td className="py-1.5 text-slate-500 w-32">Issuer</td>
                <td className="py-1.5 text-slate-300">{issuer.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-slate-500">Wallet</td>
                <td className="py-1.5 text-slate-300">{wallet.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-slate-500">Verifier</td>
                <td className="py-1.5 text-slate-300">{verifier.name}</td>
              </tr>
              <tr>
                <td className="py-1.5 text-slate-500">Format</td>
                <td className="py-1.5">
                  <span className={`text-xs font-medium px-1.5 py-0.5 rounded ${
                    credentialType.format === 'vc+sd-jwt'
                      ? 'bg-purple-500/10 text-purple-400'
                      : 'bg-green-500/10 text-green-400'
                  }`}>
                    {credentialType.name}
                  </span>
                </td>
              </tr>
              <tr>
                <td className="py-1.5 text-slate-500">Proof Type</td>
                <td className="py-1.5 text-slate-300 font-mono text-xs">{credentialType.proofTypes.join(', ')}</td>
              </tr>
            </tbody>
          </table>
        </div>

        {/* Step results */}
        <div>
          <p className="text-xs text-slate-500 mb-2">Step Results</p>
          <div className="space-y-1">
            {steps.map((step, i) => (
              <div key={step.id} className="flex items-center justify-between px-3 py-2 rounded-md bg-slate-900/50 text-sm">
                <div className="flex items-center gap-2">
                  <span className="text-slate-600 text-xs w-4">{i + 1}.</span>
                  <span className="text-slate-300">{step.label}</span>
                </div>
                <span className={`text-xs font-medium ${
                  step.status === 'done' ? 'text-green-400' :
                  step.status === 'error' ? 'text-red-400' :
                  'text-slate-500'
                }`}>
                  {step.status === 'done' ? 'pass' : step.status}
                </span>
              </div>
            ))}
          </div>
        </div>

        {/* Failure details */}
        {failedSteps.length > 0 && (
          <div className="border border-amber-500/20 rounded-md p-3 bg-amber-500/5">
            <p className="text-xs text-amber-400 font-medium mb-1">Failed Steps (Interoperability Gaps)</p>
            {failedSteps.map(s => (
              <p key={s.id} className="text-xs text-amber-300">✗ {s.label}</p>
            ))}
            <p className="text-xs text-slate-500 mt-2">
              These failures represent real interoperability gaps discovered during testing against the
              MOSIP Collab sandbox. See <span className="font-mono">INTEROPERABILITY_REPORT.md</span> for details.
            </p>
          </div>
        )}
      </div>
    </div>
  )
}
